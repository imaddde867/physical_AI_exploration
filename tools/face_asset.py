"""Reproducibly embed the one approved 240x240 indexed PNG as RGB565.

Only Python's standard library is required. The source PNG has <=32 colors,
stored in an 8-bit indexed PNG; each packed RLE token is 3-bit run length
(1..8) + 5-bit palette index (0..31). The generated header is ignored in git.
"""
from __future__ import annotations

import argparse
import hashlib
import struct
import zlib
from pathlib import Path

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
SIZE = 240


def _paeth(a: int, b: int, c: int) -> int:
    p = a + b - c
    da, db, dc = abs(p - a), abs(p - b), abs(p - c)
    if da <= db and da <= dc:
        return a
    return b if db <= dc else c


def indexed_png(source: Path) -> tuple[list[tuple[int, int, int]], bytes]:
    """Load a CRC-checked, 8-bit indexed 240x240 PNG, no Pillow dependency."""
    data = source.read_bytes()
    if not data.startswith(PNG_SIGNATURE):
        raise ValueError("Not a PNG")
    off = len(PNG_SIGNATURE)
    colors: list[tuple[int, int, int]] = []
    compressed: list[bytes] = []
    header_found = end_found = False
    while off + 12 <= len(data):
        count = struct.unpack_from(">I", data, off)[0]
        kind = data[off + 4:off + 8]
        end = off + 12 + count
        if end > len(data):
            raise ValueError("Truncated PNG chunk")
        value = data[off + 8:off + 8 + count]
        crc = struct.unpack_from(">I", data, off + 8 + count)[0]
        if zlib.crc32(kind + value) & 0xffffffff != crc:
            raise ValueError("PNG CRC mismatch")
        off = end
        if kind == b"IHDR":
            vals = struct.unpack(">IIBBBBB", value)
            if vals != (SIZE, SIZE, 8, 3, 0, 0, 0):
                raise ValueError("Expected 240x240 8-bit indexed, non-interlaced PNG")
            header_found = True
        elif kind == b"PLTE":
            if len(value) % 3 or not (1 <= len(value) // 3 <= 32):
                raise ValueError("Expected 1..32 palette colors")
            colors = [tuple(value[i:i+3]) for i in range(0, len(value), 3)]
        elif kind == b"IDAT":
            compressed.append(value)
        elif kind == b"IEND":
            end_found = True
            break
    if not (header_found and end_found and colors and compressed):
        raise ValueError("PNG missing required data")
    if sum(map(len, compressed)) > SIZE * SIZE * 3:
        raise ValueError("PNG compressed input unexpectedly large")
    decoded = zlib.decompress(b"".join(compressed))
    if len(decoded) != SIZE * (SIZE + 1):
        raise ValueError("Unexpected PNG scanline length")
    previous = bytearray(SIZE)
    rows = []
    for y in range(SIZE):
        filter_id = decoded[y * (SIZE + 1)]
        if filter_id > 4:
            raise ValueError("Unsupported PNG row filter")
        encoded = decoded[y * (SIZE + 1) + 1:(y + 1) * (SIZE + 1)]
        row = bytearray(SIZE)
        for x, byte in enumerate(encoded):
            left = row[x - 1] if x else 0
            top = previous[x]
            upper = previous[x - 1] if x else 0
            correction = (0, left, top, (left + top) // 2, _paeth(left, top, upper))[filter_id]
            row[x] = (byte + correction) & 255
        rows.append(row)
        previous = row
    pixels = b"".join(rows)
    if max(pixels) >= len(colors):
        raise ValueError("PNG palette index out of bounds")
    return colors, pixels


def rgb565(color: tuple[int, int, int]) -> int:
    r, g, b = color
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def encode_runs(pixels: bytes) -> bytes:
    if len(pixels) != SIZE * SIZE or max(pixels) > 31:
        raise ValueError("Unexpected face sprite pixels")
    tokens = bytearray()
    last, count = pixels[0], 0
    for idx in pixels:
        if idx != last or count == 8:
            tokens.append(((count - 1) << 5) | last)
            last, count = idx, 0
        count += 1
    tokens.append(((count - 1) << 5) | last)
    return bytes(tokens)


def decode_runs(tokens: bytes) -> bytes:
    out = bytearray()
    for value in tokens:
        out.extend([value & 31] * ((value >> 5) + 1))
    return bytes(out)


def generate(source: Path, header: Path) -> dict[str, str | int]:
    palette, pixels = indexed_png(source)
    tokens = encode_runs(pixels)
    if decode_runs(tokens) != pixels:
        raise AssertionError("Sprite encode/decode mismatch")
    sha = hashlib.sha256(source.read_bytes()).hexdigest()
    colors = [rgb565(c) for c in palette] + [0] * (32 - len(palette))
    lines = [
        "// Auto-generated by tools/face_asset.py. Do not edit.",
        f"// Input SHA256: {sha}",
        "#pragma once",
        "#include <Arduino.h>",
        "constexpr uint16_t kFaceWidth = 240, kFaceHeight = 240;",
        f"constexpr size_t kFaceRunCount = {len(tokens)};",
        "static const uint16_t kFacePalette[32] PROGMEM = {",
        "  " + ", ".join(f"0x{n:04X}" for n in colors),
        "};",
        "static const uint8_t kFacePackedRuns[] PROGMEM = {",
    ]
    for i in range(0, len(tokens), 24):
        lines.append("  " + ", ".join(f"0x{n:02X}" for n in tokens[i:i+24]) + ",")
    lines.extend(["};", f"static_assert(sizeof(kFacePackedRuns) == {len(tokens)}, \"Asset bytes mismatch\");", ""])
    text = "\n".join(lines)
    header.parent.mkdir(parents=True, exist_ok=True)
    if not header.exists() or header.read_text(encoding="utf-8") != text:
        header.write_text(text, encoding="utf-8")
    return {"sha256": sha, "palette_colors": len(palette), "rle_bytes": len(tokens)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("assets/face-idle-240.png"))
    parser.add_argument("--header", type=Path, default=Path("firmware/include/face_asset.h"))
    args = parser.parse_args()
    print(generate(args.source, args.header))


if __name__ == "__main__":
    main()
